export function enrichQuest(quest, collection = vendors) {
  const stops = quest.vendorIds.map((id) => collection.find((v) => v.id === id));
  return {
    ...quest,
    stops,
    budget: stops.reduce((sum, v) => sum + v.price, 0),
    stopCount: stops.length,
    dataType: stops.every((v) => v.dataType === 'illustrative') ? 'illustrative' : 'mixed',
  };
}
